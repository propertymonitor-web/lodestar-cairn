#!/usr/bin/env python3
"""Draw the CAIRN emblem (a lodestar over a stack of cairn stones) as a 1-bit bitmap.
Writes cairn/ui/CairnLogo.h (for the OLED) and docs/cairn-logo.png (preview, 8x). Original artwork."""
import pathlib
from PIL import Image, ImageDraw
W, H = 40, 60
root = pathlib.Path(__file__).resolve().parent.parent
im = Image.new("1", (W, H), 0)
d = ImageDraw.Draw(im)
# the lodestar: a four-point guiding star
cx, cy, R, r = 20, 9, 9, 2
d.polygon([(cx, cy - R), (cx + r, cy - r), (cx + R, cy), (cx + r, cy + r), (cx, cy + R), (cx - r, cy + r), (cx - R, cy), (cx - r, cy - r)], fill=1)
# the cairn: four balanced stones, widest at the bottom
stones = [(2, 49, 38, 59, 5), (7, 39, 31, 48, 4), (11, 30, 33, 38, 3), (15, 22, 26, 29, 3)]   # uneven and offset, like a real cairn
for x0, y0, x1, y1, rad in stones:
    d.rounded_rectangle((x0 - 1, y0 - 1, x1 + 1, y1 + 1), radius=rad + 1, fill=0)   # dark outline separates the stones
    d.rounded_rectangle((x0, y0, x1, y1), radius=rad, fill=1)
# a few dark flecks so each stone reads as rock
for x, y in [(10, 53), (11, 53), (28, 55), (14, 43), (22, 42), (23, 42), (19, 34), (20, 34), (18, 26)]:
    d.point((x, y), fill=0)
rows = []
for y in range(H):
    for xb in range(0, W, 8):
        v = 0
        for b in range(8):
            v = (v << 1) | (1 if xb + b < W and im.getpixel((xb + b, y)) else 0)
        rows.append(v)
lines = []
for i in range(0, len(rows), W // 8):
    lines.append("  " + ", ".join("0x%02X" % x for x in rows[i:i + W // 8]) + ",")
hdr = f"""// CAIRN emblem: a lodestar over a stack of cairn stones. {W}x{H}, 1 bit per pixel, MSB first.
// Original artwork by FEAR REACTIVE. Generated by tools/make_logo.py - do not edit by hand.
#pragma once
#include <stdint.h>
#ifndef PROGMEM
#define PROGMEM
#endif
#define CAIRN_LOGO_W {W}
#define CAIRN_LOGO_H {H}
static const uint8_t cairn_logo[] PROGMEM = {{
""" + "\n".join(lines) + "\n};\n"
(root / "cairn" / "ui" / "CairnLogo.h").write_text(hdr)
(root / "docs").mkdir(exist_ok=True)
im.convert("RGB").resize((W * 8, H * 8), Image.NEAREST).save(root / "docs" / "cairn-logo.png")
print("ok")
