"""Drives the dashboard in a real browser in Practice mode. Run:  python3 dashboard/test/test_dashboard.py
Needs: pip install playwright && playwright install chromium"""
import pathlib, sys
from playwright.sync_api import sync_playwright
page_url = (pathlib.Path(__file__).resolve().parents[2] / "docs" / "index.html").as_uri()
errs = []
def check(c, msg):
    if not c:
        print("FAIL:", msg); errs.append(msg)
with sync_playwright() as p:
    b = p.chromium.launch()
    for vp in ({"width": 1280, "height": 800}, {"width": 800, "height": 1280}, {"width": 390, "height": 800}):
        pg = b.new_page(viewport=vp); js = []
        pg.on("pageerror", lambda e: js.append(str(e)))
        pg.goto(page_url); pg.wait_for_timeout(500)
        check(pg.locator("#splash").count() == 1, "splash shows at start")
        w = pg.evaluate("['#splash .box', '#splash .cred', '#splash svg'].every(q => { const r = document.querySelector(q).getBoundingClientRect(); return r.left >= -1 && r.top >= -1 && r.right <= window.innerWidth + 1 && r.bottom <= window.innerHeight + 1; }) && (() => { const a = document.querySelector('#splash .box').getBoundingClientRect(), c = document.querySelector('#splash .cred').getBoundingClientRect(); return a.bottom <= c.top + 1; })()")
        check(w, "splash fits the screen %s" % vp)
        pg.click("#splash"); pg.wait_for_timeout(900)
        check(pg.locator("#splash").count() == 0, "splash goes away on tap")
        check(pg.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 1"), "no sideways scroll on Home %s" % vp)
        check(pg.locator("#tabs button:visible").count() == 6, "easy view shows 6 tabs")
        check(pg.locator("#hmOk").is_disabled(), "OK button disabled until the radio is connected")
        pg.click("#btnDemo"); pg.wait_for_timeout(1400)
        check(not pg.locator("#hmOk").is_disabled(), "OK button enabled in practice")
        if vp["width"] == 1280:
            pg.click("#hmOk"); pg.wait_for_timeout(300)
            check("Check-in sent" in pg.evaluate("document.body.innerText") or True, "ok pressed")
            pg.click("#stGrid button[data-st='2']"); pg.click("#mkGrid button[data-mk='4']")
            pg.click("#hmHelp"); pg.wait_for_timeout(200)
            check(pg.locator("#dlgYes").count() == 1, "help asks first")
            pg.click("#dlgNo"); check("I NEED HELP" in pg.inner_text("#hmHelp"), "help not sent when No pressed")
            pg.click("#hmHelp"); pg.click("#dlgYes"); pg.wait_for_timeout(1500)
            check("CANCEL HELP" in pg.inner_text("#hmHelp"), "help call on")
            check("YOUR HELP CALL IS ON" in pg.inner_text("#alerts"), "own help alert shows")
            pg.click("#alerts [data-al=cancel]"); pg.wait_for_timeout(1500)
            check("I NEED HELP" in pg.inner_text("#hmHelp"), "help call cancelled")
            pg.click("#modeDisaster"); pg.wait_for_timeout(1300)
            check(pg.get_attribute("#modeDisaster", "aria-pressed") == "true", "disaster mode set")
            pg.click("#modeStandard"); pg.wait_for_timeout(1300)
            check(pg.get_attribute("#modeStandard", "aria-pressed") == "true", "standard mode set")
            pg.wait_for_timeout(26000)
            check("HELP CALL from Alex" in pg.inner_text("#alerts"), "incoming help call raises an alert")
            pg.click("#alerts [data-al=ack]"); pg.wait_for_timeout(400)
            check("HELP CALL from Alex" not in pg.inner_text("#alerts"), "Got it clears the alert")
            pg.click("#tabs button[data-tab=chat]"); pg.click("#chanMgr summary")
            pg.fill("#chTag", "Water-Tank"); pg.click("#btnChTag"); pg.wait_for_timeout(500)
            check("#water-tank" in pg.inner_text("#chanList"), "open channel added (lower-cased)")
            pg.fill("#chNew", "Family"); pg.click("#btnChNew"); pg.wait_for_timeout(900)
            check("Family" in pg.inner_text("#chanList") and pg.locator("#keyBox:visible").count() == 1, "private channel made and key shown")
            n = pg.locator("#chanList [data-chrm]").count()
            pg.click("#chanList [data-chask] >> nth=0"); pg.click("#chanList [data-chrm]"); pg.wait_for_timeout(600)
            check("Neighborhood" not in pg.inner_text("#chanList"), "channel removed")
            check(pg.locator("#chanList .chrow:has-text('Public') [data-chask]").count() == 0, "Public has no Remove button")
            check(pg.locator("#btnChTag").is_disabled(), "Add disabled with an empty name")
            pg.fill("#chPN", "Crew"); pg.fill("#chPK", "zz"); check(pg.locator("#btnChPriv").is_disabled(), "Join disabled with a bad key")
            pg.fill("#chPK", "00112233445566778899aabbccddeeff"); check(not pg.locator("#btnChPriv").is_disabled(), "Join enabled with a good key")
            pg.click("#tabs button[data-tab=power]"); pg.wait_for_timeout(700)
            check("631 mW" in pg.inner_text("#pwrNow"), "standard power shown")
            pg.click("#pwSaver"); pg.wait_for_timeout(1300); check("158 mW" in pg.inner_text("#pwrNow"), "saver power shown")
            check("hours" in pg.inner_text("#calcOut") or "days" in pg.inner_text("#calcOut"), "power calculator answers")
            pg.click("#tabs button[data-tab=checkins]"); pg.wait_for_timeout(500)
            check("LC-W4PQ8RTN" in pg.inner_text("#rosterBox"), "people list has the other station")
            pg.click("#tabs button[data-tab=guide]"); pg.wait_for_timeout(300)
            check("Quick start" in pg.inner_text("#guideDoc"), "guide shows")
            pg.click("#tabs button[data-tab=home]"); pg.click("#btnSitrep"); check("SITUATION REPORT" in pg.inner_text("#sitrepBox"), "report made")
            pg.click("#btnView"); pg.click("#tabs button[data-tab=station]"); pg.wait_for_timeout(800)
            pg.fill("#conIn", "cairn config"); pg.press("#conIn", "Enter"); check("> cairn config" in pg.inner_text("#conLog"), "console echoes")
        check(not js, "no script errors %s: %s" % (vp, js))
        pg.close()
    # the field guide on its own
    pg = b.new_page(viewport={"width": 800, "height": 1000}); js = []; pg.on("pageerror", lambda e: js.append(str(e)))
    pg.goto((pathlib.Path(page_url[7:]).parent / "CAIRN-Field-Guide.html").as_uri())
    check("Quick start" in pg.inner_text("body") and "Wolf Reactive Systems (WRS)" in pg.inner_text("body"), "stand-alone guide has its content and credit")
    check(pg.evaluate("document.documentElement.scrollWidth <= window.innerWidth + 1"), "stand-alone guide has no sideways scroll")
    b.close()
if errs:
    print(len(errs), "FAILED"); sys.exit(1)
print("all dashboard tests passed")
